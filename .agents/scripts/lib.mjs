export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const HOME = homedir();
export const MARKER = "GENERATED BY seo-kit";

export function fail(message) {
  throw new Error(message);
}

export function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: options.cwd ?? ROOT,
    encoding: "utf8",
    input: options.input,
    timeout: options.timeout ?? 120_000,
    env: options.env ?? process.env,
  });
  if (!options.allowFailure && result.status !== 0) {
    fail(`${command} ${args.join(" ")} failed:\n${(result.stderr || result.stdout || result.error?.message || "unknown error").trim()}`);
  }
  return result;
}

export function commandAvailable(command) {
  return run(command, ["--version"], { allowFailure: true, timeout: 30_000 }).status === 0;
}

export function parseDocument(filePath) {
  const source = readFileSync(filePath, "utf8");
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  if (!match) fail(`${filePath}: missing YAML frontmatter`);
  return { source, frontmatter: match[1], body: match[2].trimEnd() };
}

export function scalar(frontmatter, key) {
  const line = frontmatter.split("\n").find((item) => item.startsWith(`${key}:`));
  const value = line ? line.slice(line.indexOf(":") + 1).trim() : "";
  // Quoted scalar values use JSON-compatible YAML double-quote syntax.
  return value.startsWith('"') ? JSON.parse(value) : value;
}

export function listValue(frontmatter, key) {
  const lines = frontmatter.split("\n");
  const values = [];
  let active = false;
  for (const line of lines) {
    if (line === `${key}:`) {
      active = true;
      continue;
    }
    if (active && /^  - /.test(line)) values.push(line.replace(/^  - /, "").trim());
    else if (active && line && !/^\s/.test(line)) break;
  }
  return values;
}

export function agents() {
  return readdirSync(path.join(ROOT, ".agents", "agents"), { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".md"))
    .map((entry) => {
      const filePath = path.join(ROOT, ".agents", "agents", entry.name);
      const document = parseDocument(filePath);
      const name = scalar(document.frontmatter, "name");
      return {
        ...document,
        filePath,
        name,
        description: scalar(document.frontmatter, "description"),
        tools: scalar(document.frontmatter, "tools").split(",").map((item) => item.trim()).filter(Boolean),
        skills: listValue(document.frontmatter, "skills"),
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

export function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

export function writeAtomic(filePath, content, options = {}) {
  if (existsSync(filePath) && readFileSync(filePath, "utf8") === content) return false;
  mkdirSync(path.dirname(filePath), { recursive: true });
  const temporary = `${filePath}.tmp-${process.pid}`;
  const mode = options.mode ?? (existsSync(filePath) ? statSync(filePath).mode & 0o777 : 0o644);
  writeFileSync(temporary, content, { mode });
  renameSync(temporary, filePath);
  return true;
}

export function pathPresent(filePath) {
  try {
    lstatSync(filePath);
    return true;
  } catch {
    return false;
  }
}

export function backupPath(targetPath) {
  const directory = path.join(HOME, "backups", "seo-kit");
  mkdirSync(directory, { recursive: true });
  const stamp = new Date().toISOString().replace(/[:.]/g, "-");
  const relative = path.relative(HOME, targetPath).replaceAll(path.sep, "__");
  let candidate = path.join(directory, `${relative}-${stamp}`);
  let suffix = 1;
  while (pathPresent(candidate)) candidate = `${candidate}-${suffix++}`;
  return candidate;
}

export function ensureLink(linkPath, targetPath, dryRun = false) {
  if (!existsSync(targetPath)) fail(`Cannot link missing target: ${targetPath}`);
  if (pathPresent(linkPath)) {
    const stat = lstatSync(linkPath);
    if (stat.isSymbolicLink()) {
      const current = path.resolve(path.dirname(linkPath), readlinkSync(linkPath));
      if (current === path.resolve(targetPath)) return "unchanged";
    }
    if (dryRun) return "replace";
    const backup = backupPath(linkPath);
    renameSync(linkPath, backup);
    process.stdout.write(`backup: ${linkPath} -> ${backup}\n`);
  } else if (dryRun) return "create";
  mkdirSync(path.dirname(linkPath), { recursive: true });
  symlinkSync(targetPath, linkPath, lstatSync(targetPath).isDirectory() ? "dir" : "file");
  return "linked";
}

export function removeManagedLink(linkPath, targetPath, dryRun = false) {
  if (!pathPresent(linkPath) || !lstatSync(linkPath).isSymbolicLink()) return false;
  const current = path.resolve(path.dirname(linkPath), readlinkSync(linkPath));
  if (current !== path.resolve(targetPath)) return false;
  if (!dryRun) unlinkSync(linkPath);
  return true;
}

