import { existsSync, readFileSync, unlinkSync } from "node:fs";
import path from "node:path";
import { run, writeAtomic } from "./lib.mjs";
import { assertRegularAncestors } from "./integrations.mjs";

const MARK = "GENERATED BY seo-kit";
const CRON_START = "# BEGIN seo-kit automatic updates";
const CRON_END = "# END seo-kit automatic updates";
const xml = (value) => value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;");
const ps = (value) => `'${value.replaceAll("'", "''")}'`;
const sh = (value) => `'${value.replaceAll("'", "'\\''")}'`;
const unit = (value) => `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"').replaceAll("%", "%%")}"`;

function template(name, values) {
  let content = readFileSync(new URL(`../install/${name}`, import.meta.url), "utf8");
  for (const [key, value] of Object.entries(values)) content = content.replaceAll(key, value);
  return content;
}

function managedFile(file, content, remove) {
  assertRegularAncestors(file);
  if (existsSync(file) && !readFileSync(file, "utf8").includes(MARK)) throw new Error(`Refusing to replace foreign scheduler file: ${file}`);
  if (remove) { if (existsSync(file)) unlinkSync(file); }
  else writeAtomic(file, content);
}

export function windowsRegistration(base, node) {
  const launcher = path.join(base, "seo-kit.mjs");
  return template("windows/register.ps1.in", { "{{NODE}}": ps(node), "{{ARGUMENTS}}": ps(`"${launcher}" sync`), "{{BASE}}": ps(base) });
}

export function configureUpdates({ base, paths, platform = process.platform, home, node = process.execPath, env = process.env, execute = run, remove = false, scheduler = null }) {
  const launcher = path.join(base, "seo-kit.mjs");
  for (const value of [base, node, env.PATH ?? ""]) if (/[\r\n\0]/.test(value)) throw new Error("Scheduler paths cannot contain control characters");
  const invoke = (command, args, options = {}) => execute(command, args, { cwd: base, ...options });
  if (platform === "win32") {
    const script = remove ? `# ${MARK}
$ErrorActionPreference = 'Stop'
$name = 'SEO Kit Update-' + [System.Security.Principal.WindowsIdentity]::GetCurrent().User.Value
$task = Get-ScheduledTask -TaskName $name -ErrorAction SilentlyContinue
if ($task -and $task.Description -eq '${MARK}') { Unregister-ScheduledTask -TaskName $name -Confirm:$false }
` : windowsRegistration(base, node);
    const file = path.join(base, "state", "scheduled-task.ps1");
    managedFile(file, script, false);
    // Windows PowerShell 5.1 needs a BOM for non-ASCII user names and paths.
    writeAtomic(file, `\uFEFF${script}`);
    invoke("powershell.exe", ["-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-File", file]);
    return "windows-task";
  }
  if (platform === "darwin") {
    const file = path.join(home, "Library/LaunchAgents/com.seo-kit.sync.plist");
    const content = template("launchd/com.seo-kit.sync.plist.in", {
      "{{NODE}}": xml(node), "{{LAUNCHER}}": xml(launcher), "{{PATH}}": xml(env.PATH ?? ""),
      "{{LOG}}": xml(path.join(base, "state/scheduler.log")), "{{ERROR_LOG}}": xml(path.join(base, "state/scheduler.error.log")),
    });
    // Check ownership before unloading anything.
    if (existsSync(file) && !readFileSync(file, "utf8").includes(MARK)) throw new Error(`Foreign launchd job: ${file}`);
    const domain = `gui/${process.getuid?.() ?? 0}`;
    const stopped = invoke("launchctl", ["bootout", domain, file], { allowFailure: true });
    if (stopped.status !== 0 && invoke("launchctl", ["print", `${domain}/com.seo-kit.sync`], { allowFailure: true }).status === 0) throw new Error("Cannot unload seo-kit launchd job");
    managedFile(file, content, remove);
    if (!remove) invoke("launchctl", ["bootstrap", domain, file]);
    return "launchd";
  }
  if (platform === "linux" && scheduler !== "cron" && (scheduler === "systemd" || invoke("systemctl", ["--user", "show-environment"], { allowFailure: true }).status === 0)) {
    const directory = path.join(paths.config, "systemd/user");
    const service = path.join(directory, "seo-kit-sync.service");
    const timer = path.join(directory, "seo-kit-sync.timer");
    for (const file of [service, timer]) if (existsSync(file) && !readFileSync(file, "utf8").includes(MARK)) throw new Error(`Foreign systemd unit: ${file}`);
    const stopped = invoke("systemctl", ["--user", "disable", "--now", "seo-kit-sync.timer", "seo-kit-sync.service"], { allowFailure: true });
    if (stopped.status !== 0 && ["seo-kit-sync.timer", "seo-kit-sync.service"].some((name) => invoke("systemctl", ["--user", "is-active", name], { allowFailure: true }).status === 0)) throw new Error("Cannot stop existing SEO Kit scheduler");
    managedFile(service, template("systemd/seo-kit-sync.service.in", {
      "{{NODE}}": unit(node), "{{LAUNCHER}}": unit(launcher), "{{PATH}}": unit(`PATH=${env.PATH ?? ""}`),
    }), remove);
    managedFile(timer, template("systemd/seo-kit-sync.timer.in", {}), remove);
    invoke("systemctl", ["--user", "daemon-reload"]);
    if (!remove) invoke("systemctl", ["--user", "enable", "--now", "seo-kit-sync.timer"]);
    return "systemd";
  }
  if (["linux", "freebsd", "openbsd", "netbsd", "sunos", "aix"].includes(platform)) {
    const result = invoke("crontab", ["-l"], { allowFailure: true });
    if (result.error || (result.status !== 0 && !/no crontab/i.test(result.stderr ?? ""))) throw new Error("No usable user scheduler. Install/enable systemd user timers or cron, then rerun setup. --no-services explicitly opts out.");
    const current = result.stdout ?? "";
    const pattern = /# BEGIN seo-kit automatic updates\n[\s\S]*?# END seo-kit automatic updates\n?/;
    if ((current.includes(CRON_START) || current.includes(CRON_END)) && !pattern.test(current)) throw new Error("Malformed seo-kit crontab markers");
    const cleaned = current.replace(pattern, "");
    const command = `PATH=${sh(env.PATH ?? "/usr/bin:/bin")} ${sh(node)} ${sh(launcher)} sync >> ${sh(path.join(base, "state/scheduler.log"))} 2>&1`.replaceAll("%", "\\%");
    const block = `${CRON_START}\n0 * * * * ${command}\n@reboot ${command}\n${CRON_END}\n`;
    invoke("crontab", ["-"], { input: remove ? cleaned : `${cleaned}${cleaned && !cleaned.endsWith("\n") ? "\n" : ""}${block}` });
    return "cron";
  }
  throw new Error(`Automatic updates need a scheduler adapter for ${platform}. Resources are portable. --no-services explicitly opts out.`);
}
