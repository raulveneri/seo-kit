import assert from "node:assert/strict";
import { existsSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import test from "node:test";
import { retireKnowledgeServices, retireLegacySync } from "../scripts/retire-knowledge-services.mjs";

function fixture(t, platform = "linux") {
  const home = mkdtempSync(path.join(tmpdir(), "seo-kit-services-"));
  t.after(() => rmSync(home, { recursive: true, force: true }));
  const directory = platform === "linux" ? path.join(home, ".config/systemd/user") : path.join(home, "Library/LaunchAgents");
  mkdirSync(directory, { recursive: true });
  const calls = [];
  const options = { home, platform, report() {}, execute(command, args) { calls.push([command, ...args]); return { status: 0 }; } };
  return { home, directory, calls, options };
}

test("retires installed systemd knowledge jobs and preserves synchronization and foreign files", (t) => {
  const { directory, calls, options } = fixture(t);
  const timer = path.join(directory, "seo-kit-refresh.timer");
  const service = path.join(directory, "seo-kit-refresh.service");
  const sync = path.join(directory, "seo-kit-sync.service");
  writeFileSync(timer, "# GENERATED BY seo-kit\n");
  writeFileSync(service, "custom service\n");
  writeFileSync(sync, "# GENERATED BY seo-kit\n");
  retireKnowledgeServices(options);
  assert.equal(existsSync(timer), false);
  assert.equal(readFileSync(service, "utf8"), "custom service\n");
  assert.ok(existsSync(sync));
  assert.deepEqual(calls, [
    ["systemctl", "--user", "disable", "--now", "seo-kit-refresh.timer"],
    ["systemctl", "--user", "daemon-reload"],
  ]);
  calls.length = 0;
  retireKnowledgeServices(options);
  assert.deepEqual(calls, []);
});

test("dry-run leaves legacy services untouched and executes no commands", (t) => {
  const { directory, calls, options } = fixture(t);
  const timer = path.join(directory, "seo-kit-refresh.timer");
  writeFileSync(timer, "# GENERATED BY seo-kit\n");
  retireKnowledgeServices({ ...options, dryRun: true });
  assert.ok(existsSync(timer));
  assert.deepEqual(calls, []);
});

test("a failure stopping a systemd job preserves its definition and fails migration", (t) => {
  const { directory, options } = fixture(t);
  const timer = path.join(directory, "seo-kit-refresh.timer");
  writeFileSync(timer, "# GENERATED BY seo-kit\n");
  assert.throws(() => retireKnowledgeServices({ ...options, execute() { throw new Error("unavailable"); } }), /unavailable/);
  assert.ok(existsSync(timer));
});

test("retires an already unloaded launchd job without touching synchronization", (t) => {
  const { directory, calls, options } = fixture(t, "darwin");
  const refresh = path.join(directory, "com.seo-kit.refresh.plist");
  const sync = path.join(directory, "com.seo-kit.sync.plist");
  writeFileSync(refresh, "<!-- GENERATED BY seo-kit -->");
  writeFileSync(sync, "<!-- GENERATED BY seo-kit -->");
  retireKnowledgeServices({ ...options, execute(command, args) { calls.push([command, ...args]); return { status: 1 }; } });
  assert.equal(existsSync(refresh), false);
  assert.ok(existsSync(sync));
  assert.equal(calls[0][1], "bootout");
  assert.equal(calls[1][1], "print");
});

test("legacy sync migration stops only the generated job referring to this checkout", (t) => {
  const { directory, calls, options } = fixture(t);
  const file = path.join(directory, "seo-kit-sync.service");
  const root = path.join(options.home, "checkout");
  writeFileSync(file, "# GENERATED BY seo-kit\nExecStart=/another/checkout/update\n");
  retireLegacySync({ ...options, root });
  assert.ok(existsSync(file));
  assert.deepEqual(calls, []);
  writeFileSync(file, `# GENERATED BY seo-kit\nExecStart=${root}/.agents/scripts/remote-sync.mjs watch\n`);
  retireLegacySync({ ...options, root, dryRun: true });
  assert.ok(existsSync(file));
  assert.deepEqual(calls, []);
  retireLegacySync({ ...options, root });
  assert.equal(existsSync(file), false);
  assert.equal(calls[0][2], "disable");
});
